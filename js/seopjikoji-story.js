kakao.maps.load(function () {
    const container = document.getElementById('map');
    const defaultCenter = new kakao.maps.LatLng(locations[0].lat, locations[0].lng);
    const options = {
        center: defaultCenter,
        level: 4
    };
    const map = new kakao.maps.Map(container, options);

    const infoOverlays = [];
    const markerElements = [];
    const listItems = [];
    const thumbItems = [];
    const placeListEl = document.getElementById('placeList');
    const thumbBarEl = document.getElementById('thumbScrollBar');

    locations.forEach((loc, index) => {
        const position = new kakao.maps.LatLng(loc.lat, loc.lng);

        const markerContent = document.createElement('div');
        markerContent.className = 'custom-marker';
        markerContent.innerHTML = `
            <span class="badge">${index + 1}</span>
            <span class="title">${loc.title}</span>
        `;

        const customMarkerOverlay = new kakao.maps.CustomOverlay({
            position: position,
            content: markerContent,
            yAnchor: 0.5
        });
        customMarkerOverlay.setMap(map);
        markerElements.push(markerContent);

        const infoCardEl = document.createElement('div');
        infoCardEl.className = 'custom-info-card';
        infoCardEl.innerHTML = `
            <button type="button" class="btn-close">✕</button>
            <div class="card-header">
                <div class="card-title-group">
                    <span class="card-badge">${index + 1}</span>
                    <h4>${loc.title}</h4>
                </div>
            </div>
            <div class="card-desc">${loc.desc}</div>
        `;

        const customInfoOverlay = new kakao.maps.CustomOverlay({
            position: position,
            content: infoCardEl,
            yAnchor: 0.5,
            zIndex: 20
        });

        const closeBtn = infoCardEl.querySelector('.btn-close');
        closeBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            customInfoOverlay.setMap(null);
            listItems[index].classList.remove('active');
            if (thumbItems[index]) thumbItems[index].classList.remove('active');
            markerElements[index].classList.remove('active');
        });

        infoOverlays.push(customInfoOverlay);

        const thumbItem = document.createElement('div');
        thumbItem.className = 'thumb-item';
        thumbItem.innerHTML = `
            <div class="img-wrapper">
                <img src="${loc.img}" alt="${loc.title}">
            </div>
            <span>${loc.title}</span>
        `;
        thumbItems.push(thumbItem);
        thumbBarEl.appendChild(thumbItem);

        const isValidWalkTime = loc.walkTime && loc.walkTime !== "false" && loc.walkTime !== false;
        const walkTimeHtml = isValidWalkTime
            ? `<div class="walk-info">
                <img src="https://phoenixhnr.co.kr/images/ko/experience/ico-address.png" alt="위치 아이콘" class="ico-address">
                <span>B동 기준 ${loc.walkTime}</span>
               </div>`
            : '';

        const isValidLink = loc.link && loc.link !== "false" && loc.link !== false;
        const linkHtml = isValidLink
            ? `<a href="${loc.link}" class="detail-link" target="_blank" onclick="event.stopPropagation();">자세히 보기</a>`
            : '';

        const listItem = document.createElement('li');
        listItem.className = 'place-item';
        listItem.innerHTML = `
            <div class="item-header">
                <img src="${loc.img}" alt="${loc.title}" class="list-thumb">
                <div class="item-info">
                    <h3><span class="num">${index + 1}. </span>${loc.title}</h3>
                    <div class="basic-desc">${loc.desc}</div>
                </div>
            </div>
            <div class="detail-box">
                <h2 class="detail-title"><span class="num">${index + 1}. </span>${loc.title}</h2>
                <img src="${loc.img}" alt="${loc.title}" class="detail-img">
                <div class="detail-desc">${loc.detailDesc}</div>
                ${walkTimeHtml}
                ${linkHtml}
            </div>
        `;

        listItems.push(listItem);
        placeListEl.appendChild(listItem);

        const handleClick = () => selectPlace(index);
        listItem.addEventListener('click', handleClick);
        thumbItem.addEventListener('click', handleClick);
        markerContent.addEventListener('click', handleClick);
    });

    function selectPlace(index) {
        const isPc = window.innerWidth > 820;
        const isAlreadyActive = listItems[index].classList.contains('active');

        infoOverlays.forEach(overlay => overlay.setMap(null));
        listItems.forEach(item => item.classList.remove('active'));
        thumbItems.forEach(item => item.classList.remove('active'));
        markerElements.forEach(el => el.classList.remove('active'));

        if (isPc && isAlreadyActive) {
            return;
        }

        const targetInfoOverlay = infoOverlays[index];
        const targetLoc = locations[index];
        const moveLatLon = new kakao.maps.LatLng(targetLoc.lat, targetLoc.lng);

        map.panTo(moveLatLon);
        targetInfoOverlay.setMap(map);
        listItems[index].classList.add('active');
        thumbItems[index].classList.add('active');
        markerElements[index].classList.add('active');

        thumbItems[index].scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });

        if (isPc) {
            listItems[index].scrollIntoView({ behavior: 'smooth', block: 'nearest' });
        }
    }

    selectPlace(0);

    window.addEventListener('resize', () => {
        map.relayout();
    });
});